"""Generate csp_schema_data.h (C) from a .clip file written by Clip Studio Paint.

The header carries CSP's own schema registry (the CREATE TABLE statements,
the ElemScheme and ParamScheme rows) so that files written by libclip
declare the same schema CSP declares.  Only metadata is copied: no document
content leaves the reference file.

usage: python gen_csp_schema.py reference.clip ../src/csp_schema_data.h
"""
import sqlite3, struct, sys, tempfile, os

def sqlite_image(path):
    d = open(path, "rb").read()
    assert d[:8] == b"CSFCHUNK"
    pos = 24
    while pos + 16 <= len(d):
        tag = d[pos:pos + 8]; size = struct.unpack(">Q", d[pos + 8:pos + 16])[0]
        if tag == b"CHNKSQLi":
            return d[pos + 16:pos + 16 + size]
        pos += 16 + size
    raise SystemExit("no CHNKSQLi chunk")

def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main():
    src, dst = sys.argv[1], sys.argv[2]
    img = sqlite_image(src)
    tmp = tempfile.NamedTemporaryFile(delete=False, suffix=".sqlite"); tmp.write(img); tmp.close()
    db = sqlite3.connect(tmp.name)
    out = ["/* Generated by gen/gen_csp_schema.py from a Clip Studio Paint document.",
           " * Schema registry only (table definitions, ElemScheme, ParamScheme). */",
           "#ifndef LIBCLIP_CSP_SCHEMA_DATA_H", "#define LIBCLIP_CSP_SCHEMA_DATA_H", "",
           "#include <stddef.h>", ""]
    tables = db.execute("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()
    out.append("typedef struct csp_table_def { const char *name; const char *sql; } csp_table_def;")
    out.append("static const csp_table_def csp_schema_tables[] = {")
    for name, sql in tables:
        out.append(f"    {{{cstr(name)}, {cstr(sql)}}},")
    out.append("};")
    out.append("#define CSP_SCHEMA_TABLE_COUNT (sizeof(csp_schema_tables) / sizeof(csp_schema_tables[0]))")
    idx = db.execute("SELECT name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY rowid").fetchall()
    out.append("static const char *const csp_schema_indexes[] = {")
    for name, sql in idx:
        out.append(f"    {cstr(sql)},")
    out.append("};")
    out.append("#define CSP_SCHEMA_INDEX_COUNT (sizeof(csp_schema_indexes) / sizeof(csp_schema_indexes[0]))")
    out.append("typedef struct csp_elem_scheme_row { const char *table; long long elem_type; long long max_index; } csp_elem_scheme_row;")
    out.append("static const csp_elem_scheme_row csp_schema_elem_scheme[] = {")
    for t, et, mi in db.execute("SELECT TableName, ElemType, MaxIndex FROM ElemScheme ORDER BY _PW_ID"):
        out.append(f"    {{{cstr(t)}, {et}, {mi}}},")
    out.append("};")
    out.append("#define CSP_SCHEMA_ELEM_SCHEME_COUNT (sizeof(csp_schema_elem_scheme) / sizeof(csp_schema_elem_scheme[0]))")
    out.append("typedef struct csp_param_scheme_row { const char *table; const char *label; long long data_type; long long flag; long long owner_type; long long lock_type; long long lock_specified; const char *link_table; } csp_param_scheme_row;")
    out.append("static const csp_param_scheme_row csp_schema_param_scheme[] = {")
    for t, l, dt, fl, ot, lt, ls, link in db.execute("SELECT TableName, LabelName, DataType, Flag, OwnerType, LockType, LockSpecified, LinkTable FROM ParamScheme ORDER BY _PW_ID"):
        out.append(f"    {{{cstr(t)}, {cstr(l)}, {dt}, {fl}, {ot}, {lt}, {ls}, {cstr(link or '')}}},")
    out.append("};")
    out.append("#define CSP_SCHEMA_PARAM_SCHEME_COUNT (sizeof(csp_schema_param_scheme) / sizeof(csp_schema_param_scheme[0]))")
    out.append("")
    out.append("#endif")
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    db.close(); os.unlink(tmp.name)
    print(f"wrote {dst}: {len(tables)} tables, {len(idx)} indexes")

if __name__ == "__main__":
    main()
